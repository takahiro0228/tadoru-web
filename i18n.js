    /** 日本語の文字列を、いまの言語に合わせて置き換えます。一致しなければそのまま返します。 */
    function translate(text, lang) {
        const source = String(text ?? "");
        if (lang !== "en" || !source) return source;
        const trimmed = source.trim();
        if (!trimmed) return source;
        const hit = EN[trimmed];
        if (hit !== undefined) return source.replace(trimmed, hit);
        for (let i = 0; i < EN_PATTERNS.length; i += 1) {
            const [pattern, replacement] = EN_PATTERNS[i];
            if (!pattern.test(trimmed)) continue;
            // 捕捉した部分も辞書で引き直します（例:「システム標準（既定）」→「System default (default)」）。
            const applied = trimmed.replace(pattern, (...args) => {
                const groups = args.slice(1, -2).map((group) => (group === undefined ? group : (EN[String(group).trim()] ?? group)));
                return String(replacement).replace(/\$(\d)/g, (_m, index) => {
                    const value = groups[Number(index) - 1];
                    return value === undefined ? "" : String(value);
                });
            });
            return source.replace(trimmed, applied);
        }
        return source;
    }

